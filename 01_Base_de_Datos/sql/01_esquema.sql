-- Solo para la base nueva dw_mef_2022_2025. La transaccion completa la controla etl.py.
CREATE SCHEMA mef;

CREATE TABLE mef.dim_anio (
 anio_key SMALLINT PRIMARY KEY,
 anio SMALLINT NOT NULL UNIQUE,
 CHECK (anio_key = anio AND anio BETWEEN 2022 AND 2025)
);

CREATE TABLE mef.dim_entidad (
 entidad_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clave_natural TEXT NOT NULL UNIQUE CHECK (jsonb_typeof(clave_natural::jsonb) = 'array'),
 "nivel_gobierno" TEXT NOT NULL,
 "sector" TEXT NOT NULL,
 "pliego" TEXT NOT NULL,
 "ejecutora" TEXT NOT NULL,
 "sec_ejec" TEXT NOT NULL,
 "departamento_ejecutora" TEXT NOT NULL,
 "provincia_ejecutora" TEXT NOT NULL,
 "distrito_ejecutora" TEXT NOT NULL,
 "nivel_gobierno_nombre" TEXT NOT NULL,
 "sector_nombre" TEXT NOT NULL,
 "pliego_nombre" TEXT NOT NULL,
 "ejecutora_nombre" TEXT NOT NULL,
 "departamento_ejecutora_nombre" TEXT NOT NULL,
 "provincia_ejecutora_nombre" TEXT NOT NULL,
 "distrito_ejecutora_nombre" TEXT NOT NULL,
 nombres_observados JSONB NOT NULL CHECK (jsonb_typeof(nombres_observados) = 'object')
);

CREATE TABLE mef.dim_intervencion (
 intervencion_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clave_natural TEXT NOT NULL UNIQUE CHECK (jsonb_typeof(clave_natural::jsonb) = 'array'),
 "programa_ppto" TEXT NOT NULL,
 "tipo_act_proy" TEXT NOT NULL,
 "producto_proyecto" TEXT NOT NULL,
 "actividad_accion_obra" TEXT NOT NULL,
 "programa_ppto_nombre" TEXT NOT NULL,
 "tipo_act_proy_nombre" TEXT NOT NULL,
 "producto_proyecto_nombre" TEXT NOT NULL,
 "actividad_accion_obra_nombre" TEXT NOT NULL,
 nombres_observados JSONB NOT NULL CHECK (jsonb_typeof(nombres_observados) = 'object')
);

CREATE TABLE mef.dim_funcion (
 funcion_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clave_natural TEXT NOT NULL UNIQUE CHECK (jsonb_typeof(clave_natural::jsonb) = 'array'),
 "funcion" TEXT NOT NULL,
 "division_funcional" TEXT NOT NULL,
 "grupo_funcional" TEXT NOT NULL,
 "funcion_nombre" TEXT NOT NULL,
 "division_funcional_nombre" TEXT NOT NULL,
 "grupo_funcional_nombre" TEXT NOT NULL,
 nombres_observados JSONB NOT NULL CHECK (jsonb_typeof(nombres_observados) = 'object')
);

CREATE TABLE mef.dim_meta (
 meta_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clave_natural TEXT NOT NULL UNIQUE CHECK (jsonb_typeof(clave_natural::jsonb) = 'array'),
 anio SMALLINT NOT NULL CHECK (anio BETWEEN 2022 AND 2025),
 "meta" TEXT NOT NULL,
 "meta_nombre" TEXT NOT NULL,
 "departamento_meta" TEXT NOT NULL,
 "departamento_meta_nombre" TEXT NOT NULL,
 nombres_observados JSONB NOT NULL CHECK (jsonb_typeof(nombres_observados) = 'object')
);

CREATE TABLE mef.dim_financiamiento (
 financiamiento_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clave_natural TEXT NOT NULL UNIQUE CHECK (jsonb_typeof(clave_natural::jsonb) = 'array'),
 "fuente_financiamiento" TEXT NOT NULL,
 "rubro" TEXT NOT NULL,
 "tipo_recurso" TEXT NOT NULL,
 "fuente_financiamiento_nombre" TEXT NOT NULL,
 "rubro_nombre" TEXT NOT NULL,
 "tipo_recurso_nombre" TEXT NOT NULL,
 nombres_observados JSONB NOT NULL CHECK (jsonb_typeof(nombres_observados) = 'object')
);

CREATE TABLE mef.dim_clasificador_gasto (
 clasificador_gasto_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 clave_natural TEXT NOT NULL UNIQUE CHECK (jsonb_typeof(clave_natural::jsonb) = 'array'),
 "categoria_gasto" TEXT NOT NULL,
 "tipo_transaccion" TEXT NOT NULL,
 "generica" TEXT NOT NULL,
 "subgenerica" TEXT NOT NULL,
 "subgenerica_det" TEXT NOT NULL,
 "especifica" TEXT NOT NULL,
 "especifica_det" TEXT NOT NULL,
 "categoria_gasto_nombre" TEXT NOT NULL,
 "generica_nombre" TEXT NOT NULL,
 "subgenerica_nombre" TEXT NOT NULL,
 "subgenerica_det_nombre" TEXT NOT NULL,
 "especifica_nombre" TEXT NOT NULL,
 "especifica_det_nombre" TEXT NOT NULL,
 nombres_observados JSONB NOT NULL CHECK (jsonb_typeof(nombres_observados) = 'object')
);

CREATE TABLE mef.fact_ejecucion_presupuestaria_anual (
 hecho_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 anio_key SMALLINT NOT NULL REFERENCES mef.dim_anio(anio_key),
 entidad_key BIGINT NOT NULL REFERENCES mef.dim_entidad(entidad_key),
 intervencion_key BIGINT NOT NULL REFERENCES mef.dim_intervencion(intervencion_key),
 funcion_key BIGINT NOT NULL REFERENCES mef.dim_funcion(funcion_key),
 meta_key BIGINT NOT NULL REFERENCES mef.dim_meta(meta_key),
 financiamiento_key BIGINT NOT NULL REFERENCES mef.dim_financiamiento(financiamiento_key),
 clasificador_gasto_key BIGINT NOT NULL REFERENCES mef.dim_clasificador_gasto(clasificador_gasto_key),
 key_value TEXT NOT NULL CHECK (key_value ~ '^[0-9A-Fa-f]{32}$'),
 pia NUMERIC(20,2) NOT NULL,
 pim NUMERIC(20,2) NOT NULL,
 certificado NUMERIC(20,2) NOT NULL,
 comprometido_anual NUMERIC(20,2) NOT NULL,
 comprometido NUMERIC(20,2) NOT NULL,
 devengado NUMERIC(20,2) NOT NULL,
 girado NUMERIC(20,2) NOT NULL,
 hash_seleccion CHAR(64) NOT NULL CHECK (hash_seleccion ~ '^[0-9a-f]{64}$'),
 poblacion_estrato BIGINT NOT NULL,
 cuota_estrato BIGINT NOT NULL CHECK (cuota_estrato > 0 AND cuota_estrato <= poblacion_estrato),
 UNIQUE (anio_key,key_value),
 UNIQUE (anio_key,entidad_key,intervencion_key,funcion_key,meta_key,financiamiento_key,clasificador_gasto_key)
);

CREATE INDEX fact_entidad_idx ON mef.fact_ejecucion_presupuestaria_anual(entidad_key);
CREATE INDEX fact_funcion_idx ON mef.fact_ejecucion_presupuestaria_anual(funcion_key);
CREATE INDEX fact_financiamiento_idx ON mef.fact_ejecucion_presupuestaria_anual(financiamiento_key);
