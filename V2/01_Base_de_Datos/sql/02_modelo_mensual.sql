CREATE SCHEMA auditoria;
ALTER TABLE mef.fact_ejecucion_presupuestaria_anual ADD CONSTRAINT anual_contexto_uq
 UNIQUE(hecho_key,anio_key,entidad_key,intervencion_key,funcion_key,meta_key,financiamiento_key,clasificador_gasto_key);

CREATE TABLE mef.dim_periodo_mensual (
 periodo_key INTEGER PRIMARY KEY,
 anio_key SMALLINT NOT NULL REFERENCES mef.dim_anio,
 mes SMALLINT NOT NULL CHECK(mes BETWEEN 1 AND 12),
 mes_nombre TEXT NOT NULL,
 CHECK(periodo_key=anio_key*100+mes),
 UNIQUE(anio_key,mes), UNIQUE(periodo_key,anio_key)
);
CREATE TABLE mef.dim_meta_detallada (
 meta_detalle_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 anio_key SMALLINT NOT NULL REFERENCES mef.dim_anio,
 entidad_key BIGINT NOT NULL REFERENCES mef.dim_entidad,
 intervencion_key BIGINT NOT NULL REFERENCES mef.dim_intervencion,
 funcion_key BIGINT NOT NULL REFERENCES mef.dim_funcion,
 sec_func TEXT NOT NULL CHECK(sec_func<>''),
 finalidad TEXT NOT NULL CHECK(finalidad<>''),
 meta TEXT NOT NULL CHECK(meta<>''),
 departamento_meta TEXT NOT NULL CHECK(departamento_meta<>''),
 meta_nombre TEXT NOT NULL,
 departamento_meta_nombre TEXT NOT NULL,
 clave_natural TEXT NOT NULL UNIQUE CHECK(jsonb_typeof(clave_natural::jsonb)='array'),
 UNIQUE(anio_key,entidad_key,intervencion_key,funcion_key,sec_func,finalidad,meta,departamento_meta),
 UNIQUE(meta_detalle_key,anio_key,entidad_key,intervencion_key,funcion_key)
);
CREATE TABLE auditoria.serie_seleccionada (
 hecho_anual_key BIGINT PRIMARY KEY,
 anio_key SMALLINT NOT NULL,
 entidad_key BIGINT NOT NULL,
 intervencion_key BIGINT NOT NULL,
 funcion_key BIGINT NOT NULL,
 meta_key BIGINT NOT NULL,
 financiamiento_key BIGINT NOT NULL,
 clasificador_gasto_key BIGINT NOT NULL,
 meta_detalle_key BIGINT NOT NULL,
 fuente_grano_json TEXT NOT NULL UNIQUE CHECK(jsonb_typeof(fuente_grano_json::jsonb)='array'),
 fuente_sha256 CHAR(64) NOT NULL CHECK(fuente_sha256 ~ '^[0-9a-f]{64}$'),
 semilla TEXT NOT NULL,
 prioridad_hash CHAR(64) NOT NULL CHECK(prioridad_hash ~ '^[0-9a-f]{64}$'),
 entidad_natural TEXT NOT NULL,
 poblacion_estrato INTEGER NOT NULL,
 cuota_estrato INTEGER NOT NULL CHECK(cuota_estrato BETWEEN 1 AND poblacion_estrato),
 FOREIGN KEY(hecho_anual_key,anio_key,entidad_key,intervencion_key,funcion_key,meta_key,financiamiento_key,clasificador_gasto_key)
 REFERENCES mef.fact_ejecucion_presupuestaria_anual(hecho_key,anio_key,entidad_key,intervencion_key,funcion_key,meta_key,financiamiento_key,clasificador_gasto_key),
 FOREIGN KEY(meta_detalle_key,anio_key,entidad_key,intervencion_key,funcion_key)
 REFERENCES mef.dim_meta_detallada(meta_detalle_key,anio_key,entidad_key,intervencion_key,funcion_key),
 UNIQUE(hecho_anual_key,anio_key,entidad_key,intervencion_key,funcion_key,meta_detalle_key,financiamiento_key,clasificador_gasto_key)
);
CREATE TABLE mef.fact_devengado_mensual (
 hecho_mensual_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 hecho_anual_key BIGINT NOT NULL,
 periodo_key INTEGER NOT NULL,
 anio_key SMALLINT NOT NULL,
 entidad_key BIGINT NOT NULL REFERENCES mef.dim_entidad,
 intervencion_key BIGINT NOT NULL REFERENCES mef.dim_intervencion,
 funcion_key BIGINT NOT NULL REFERENCES mef.dim_funcion,
 meta_detalle_key BIGINT NOT NULL,
 financiamiento_key BIGINT NOT NULL REFERENCES mef.dim_financiamiento,
 clasificador_gasto_key BIGINT NOT NULL REFERENCES mef.dim_clasificador_gasto,
 devengado NUMERIC(20,2) NOT NULL,
 FOREIGN KEY(periodo_key,anio_key) REFERENCES mef.dim_periodo_mensual(periodo_key,anio_key),
 FOREIGN KEY(meta_detalle_key,anio_key,entidad_key,intervencion_key,funcion_key)
 REFERENCES mef.dim_meta_detallada(meta_detalle_key,anio_key,entidad_key,intervencion_key,funcion_key),
 FOREIGN KEY(hecho_anual_key,anio_key,entidad_key,intervencion_key,funcion_key,meta_detalle_key,financiamiento_key,clasificador_gasto_key)
 REFERENCES auditoria.serie_seleccionada(hecho_anual_key,anio_key,entidad_key,intervencion_key,funcion_key,meta_detalle_key,financiamiento_key,clasificador_gasto_key),
 UNIQUE(hecho_anual_key,periodo_key),
 UNIQUE(periodo_key,entidad_key,intervencion_key,funcion_key,meta_detalle_key,financiamiento_key,clasificador_gasto_key)
);
CREATE INDEX mensual_periodo_idx ON mef.fact_devengado_mensual(periodo_key);
CREATE INDEX mensual_entidad_idx ON mef.fact_devengado_mensual(entidad_key);
CREATE INDEX mensual_clasificador_idx ON mef.fact_devengado_mensual(clasificador_gasto_key);
CREATE VIEW mef.v_financiamiento_conformado AS
 SELECT financiamiento_key,rubro AS fuente_financiamiento,fuente_financiamiento AS rubro,
 rubro_nombre AS fuente_financiamiento_nombre,fuente_financiamiento_nombre AS rubro_nombre,
 tipo_recurso,tipo_recurso_nombre FROM mef.dim_financiamiento;
CREATE VIEW mef.v_anual_cohorte_mensual AS
 SELECT a.* FROM mef.fact_ejecucion_presupuestaria_anual a
 WHERE EXISTS(SELECT 1 FROM auditoria.serie_seleccionada s WHERE s.hecho_anual_key=a.hecho_key);
